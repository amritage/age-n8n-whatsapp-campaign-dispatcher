'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.join(__dirname,'..','workflows');
const get=(f)=>JSON.parse(fs.readFileSync(path.join(root,f),'utf8'));
const TYPES={espo:'@traien/n8n-nodes-espocrm.espoCrm',chatwoot:'@renatoascencio/n8n-nodes-chatwoot.chatwoot'};
const a=get('age-api-readiness-native.json');
const b=get('age-chatwoot-recipient-report-native.json');
const ids=new Set();
for(const w of [a,b]){
 assert(w.id&&!ids.has(w.id));ids.add(w.id);
 assert.equal(w.active,false);
 assert(w.nodes.some(x=>x.type==='n8n-nodes-base.manualTrigger'));
 assert(!w.nodes.some(x=>x.type==='n8n-nodes-base.scheduleTrigger'));
 assert.equal(w.settings.saveDataSuccessExecution,'none');
 assert.equal(w.settings.saveDataErrorExecution,'none');
 assert.equal(w.settings.saveManualExecutions,false);
 assert(!w.nodes.some(x=>x.credentials),'No credentials can be exported');
 assert(!w.nodes.some(x=>x.type==='n8n-nodes-base.postgres'||x.type==='n8n-nodes-base.executeCommand'));
}
const community=a.nodes.filter(x=>x.type===TYPES.espo||x.type===TYPES.chatwoot);
assert.equal(community.length,3,'EspoCRM get + Chatwoot get + Chatwoot metrics');
const espo=community.find(x=>x.type===TYPES.espo);
assert.equal(espo.parameters.operation,'get');
assert.equal(espo.parameters.resource,'customEntity');
assert.equal(espo.parameters.entityType,'Campaign');
const chat=a.nodes.filter(x=>x.type===TYPES.chatwoot);
assert.deepEqual(chat.map(x=>x.parameters.operation).sort(),['get','getMetrics']);
assert(chat.every(x=>x.parameters.resource==='campaign'));
const http=a.nodes.filter(x=>x.type==='n8n-nodes-base.httpRequest');
assert.equal(http.length,1,'Only custom AGE summary may use HTTP');
assert.equal(http[0].parameters.method,'GET');
assert(http[0].parameters.url.includes('/api/v1/AGECampaign/summary/'));
assert.equal(http[0].parameters.genericAuthType,'httpHeaderAuth');
assert.equal(b.nodes.filter(x=>x.type==='n8n-nodes-base.httpRequest').length,0);
assert.equal(b.nodes.filter(x=>x.type===TYPES.chatwoot).length,2);
const recipients=b.nodes.find(x=>x.parameters?.operation==='getRecipients');
assert.equal(recipients.parameters.returnAll,true);
assert.deepEqual(recipients.parameters.options,{});
const metrics=b.nodes.find(x=>x.parameters?.operation==='getMetrics');
assert(metrics&&metrics.parameters.resource==='campaign');
assert(b.nodes.find(x=>x.name==='Return Safe Aggregate Report').parameters.jsCode.includes('crmEventWriteAuthorized:false'));
assert(!JSON.stringify([a,b]).includes('api_access_token'));
assert(!JSON.stringify([a,b]).includes('X-Api-Key'));
const discovery=get('age-chatwoot-find-campaign-ids-readonly.json');
assert.equal(discovery.active,false);
assert(discovery.nodes.some(x=>x.type==='n8n-nodes-base.manualTrigger'));
assert(!discovery.nodes.some(x=>x.type==='n8n-nodes-base.scheduleTrigger'));
assert.equal(discovery.nodes.filter(x=>x.type===TYPES.chatwoot).length,1);
assert(discovery.nodes.some(x=>x.type===TYPES.chatwoot&&x.parameters.resource==='campaign'&&x.parameters.operation==='getAll'));
assert(!discovery.nodes.some(x=>x.type==='n8n-nodes-base.httpRequest'));
assert(!discovery.nodes.some(x=>x.credentials));
assert(discovery.nodes.find(x=>x.name==='Show Campaign IDs Only').parameters.jsCode.includes('No Chatwoot campaigns found'));
console.log('PASS: native EspoCRM + Chatwoot community node contracts, only one custom GET fallback, campaign discovery, no sending, no credentials');
